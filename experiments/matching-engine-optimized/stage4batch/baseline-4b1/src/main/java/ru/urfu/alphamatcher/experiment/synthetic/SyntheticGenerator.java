package ru.urfu.alphamatcher.experiment.synthetic;

import java.util.ArrayList;
import java.util.Collections;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;
import java.util.SplittableRandom;

/** Scenario-first oracle. Deliberately has no dependency on parser, name resolver or matching rules. */
public final class SyntheticGenerator {
    public static final long FIRST_ID = 1_000_000;
    public enum Scenario {
        CLEAR, MULTIPLE_CONTRACTS, SAME_NAME, THIRD_PARTY, DECLINED_NAME, ORGANIZATION,
        MISSING_INN, MISSING_NUMBER, CONFLICT, NO_CONTRACT, PROCESSED, INVALID_INN,
        UNUSUAL, UNKNOWN_NAME, ROLE_SWAP, NAME_CONFLICT, SERVICE_PHRASE, BENEFICIARY,
        DUPLICATE_NUMBER, INCOMPLETE_PARTY, LONG_TEXT, OVER_LIMIT
    }
    public enum Profile { SIMPLE, MIXED, STRESS }
    public record Config(long seed, int clients, int contracts, int operations, Profile profile,
                         Map<Scenario, Integer> weights) {
        public Config {
            if (clients < 12 || contracts < 16 || operations < 1 || operations > 2_000_000 || clients > 1_000_000 || contracts > 2_000_000)
                throw new IllegalArgumentException("Нужны >=12 клиентов, >=16 договоров, >=1 операций; предел клиентов 1M, договоров 2M");
            var copy = new EnumMap<Scenario, Integer>(Scenario.class);
            copy.putAll(weights);
            if (copy.values().stream().anyMatch(weight -> weight < 0) || copy.values().stream().mapToLong(Integer::longValue).sum() == 0)
                throw new IllegalArgumentException("Вес должен быть неотрицательным, сумма - положительной");
            weights = Collections.unmodifiableMap(copy);
        }
        public static Config standard(long seed, int clients, int contracts, int operations, Profile profile) {
            var weights = new EnumMap<Scenario, Integer>(Scenario.class);
            for (Scenario scenario : Scenario.values()) weights.put(scenario, 0);
            if (profile == Profile.SIMPLE) {
                weights.put(Scenario.CLEAR, 60); weights.put(Scenario.ORGANIZATION, 20);
                weights.put(Scenario.SERVICE_PHRASE, 10); weights.put(Scenario.UNUSUAL, 10);
            } else {
                for (Scenario scenario : Scenario.values()) weights.put(scenario, 1);
                weights.put(Scenario.CLEAR, profile == Profile.MIXED ? 10 : 1);
                weights.put(Scenario.ORGANIZATION, 3);
                weights.put(Scenario.THIRD_PARTY, profile == Profile.STRESS ? 5 : 2);
                weights.put(Scenario.SAME_NAME, profile == Profile.STRESS ? 4 : 1);
            }
            return new Config(seed, clients, contracts, operations, profile, weights);
        }
    }
    public record Client(long id, String type, String inn, String last, String first, String middle, String name) { }
    public record Contract(long id, String number, long payer, long recipient, Long beneficiary) { }
    public record Payment(long id, String reference, String purpose, String status, Long linked,
                          Long payer, long recipient, String payerInn, String recipientInn) { }
    public record Truth(long id, Scenario scenario, String expectedStatus, Long safeContract, Long knownTarget,
                        List<String> inns, List<String> invalidInns, List<String> names,
                        List<String> numbers, List<String> organizations, boolean thirdParty) { }
    public record Dataset(Config config, List<Client> clients, List<Contract> contracts, List<Payment> payments, List<Truth> truth) {
        public Dataset {
            clients = List.copyOf(clients); contracts = List.copyOf(contracts);
            payments = List.copyOf(payments); truth = List.copyOf(truth);
        }
    }
    // Independent nominative/genitive examples and canonical oracle keys, not generated by NameNormalizer.
    private static final String[][] PEOPLE = {
            {"Иванов", "Иван", "Иванович", "Иванова Ивана Ивановича", "иванов иван иванович"},
            {"Сидорова", "Анна", "Сергеевна", "Сидоровой Анны Сергеевны", "сидорова анна сергеевна"},
            {"Петров", "Пётр", "Петрович", "Петрова Петра Петровича", "петров петр петрович"},
            {"Ким", "Мария", "Андреевна", "Ким Марии Андреевны", "ким мария андреевна"},
            {"Шевченко", "Павел", "Олегович", "Шевченко Павла Олеговича", "шевченко павел олегович"},
            {"Смирнова", "Елена", "Игоревна", "Смирновой Елены Игоревны", "смирнова елена игоревна"}
    };

    public Dataset generate(Config config) {
        var random = new SplittableRandom(config.seed());
        List<Client> clients = new ArrayList<>();
        long offset = Math.floorMod(config.seed(), 100_000L);
        for (int i = 0; i < config.clients(); i++) {
            String[] person = PEOPLE[i % PEOPLE.length];
            String type = i % 3 == 2 ? "LEGAL_ENTITY" : i % 3 == 1 ? "ENTREPRENEUR" : "INDIVIDUAL";
            boolean legal = type.equals("LEGAL_ENTITY");
            String inn = legal ? legalInn(990_000_000L + (offset + i) % 1_000_000)
                    : personalInn(9_900_000_000L + offset + i);
            long id = FIRST_ID + i;
            clients.add(new Client(id, type, inn, legal ? null : person[0], legal ? null : person[1],
                    legal ? null : person[2], legal ? "ООО «Синтез " + id + "»"
                            : type.equals("ENTREPRENEUR") ? "ИП " + person[0] + " " + person[1] + " " + person[2] : null));
        }
        List<Contract> contracts = new ArrayList<>();
        for (int i = 0; i < config.contracts(); i++) {
            int payerIndex = switch (i) { case 0, 2, 4, 5 -> 0; case 1 -> 2; case 3, 8 -> 6;
                case 6 -> 1; case 7 -> 3; case 9 -> 4; default -> i % (clients.size() - 1); };
            String number = i == 2 || i == 3 ? "DUP-" + config.seed() : switch (i % 3) {
                case 0 -> "AG-" + (FIRST_ID + i); case 1 -> "КР/2026/" + (FIRST_ID + i); default -> "X." + (FIRST_ID + i) + "-А";
            };
            contracts.add(new Contract(FIRST_ID + i, number, clients.get(payerIndex).id(), clients.getLast().id(),
                    i == 4 ? clients.get(3).id() : null));
        }
        List<Contract> safePool = contracts.stream().filter(c -> c.id() != FIRST_ID + 2 && c.id() != FIRST_ID + 3 && c.beneficiary() == null).toList();
        List<Contract> organizationPool = safePool.stream().filter(c -> clients.get((int)(c.payer()-FIRST_ID)).type().equals("LEGAL_ENTITY")).toList();
        List<Scenario> plan = plan(config, random);
        List<Payment> payments = new ArrayList<>();
        List<Truth> truth = new ArrayList<>();
        for (int i = 0; i < plan.size(); i++) {
            Scenario scenario = plan.get(i);
            Contract contract = switch (scenario) {
                case MULTIPLE_CONTRACTS, SAME_NAME, MISSING_NUMBER -> contracts.get(0);
                case ORGANIZATION -> organizationPool.get(random.nextInt(organizationPool.size()));
                case DUPLICATE_NUMBER -> contracts.get(2);
                case BENEFICIARY -> contracts.get(4);
                case DECLINED_NAME -> contracts.get(new int[]{0,6,7,9}[random.nextInt(4)]);
                default -> safePool.get(random.nextInt(safePool.size()));
            };
            Client payer = clients.get((int)(contract.payer() - FIRST_ID));
            Client recipient = clients.get((int)(contract.recipient() - FIRST_ID));
            long id = FIRST_ID + i;
            String number = contract.number(), inn = payer.inn();
            String status = "SAFE", operationStatus = "LOADED";
            Long target = contract.id(), safe = contract.id(), linked = null, payerId = payer.id();
            List<String> expectedNames = new ArrayList<>(), orgs = new ArrayList<>(), invalid = new ArrayList<>();
            boolean withNumber = true, withInn = true, third = false;
            String extra = "";
            switch (scenario) {
                case CLEAR -> { }
                case MULTIPLE_CONTRACTS -> { status="REVIEW"; withNumber=false; target=null; }
                case SAME_NAME -> { status="REVIEW"; withNumber=false; withInn=false; target=null;
                    extra=", ФИО Иванов Иван Иванович"; expectedNames.add("иванов иван иванович"); }
                case THIRD_PARTY -> { status="REVIEW"; third=true;
                    int person = differentPerson(payer,recipient);
                    extra=", за " + PEOPLE[person][3]; expectedNames.add(PEOPLE[person][4]); }
                case DECLINED_NAME -> { status="REVIEW"; withInn=false;
                    int person=(int)(payer.id()-FIRST_ID)%PEOPLE.length;
                    extra=", ФИО " + PEOPLE[person][3]; expectedNames.add(PEOPLE[person][4]);
                    withNumber = random.nextBoolean(); }
                case ORGANIZATION -> { extra=", ООО \"Синтез " + payer.id() + "\""; orgs.add("ооо синтез " + payer.id()); }
                case MISSING_INN -> { status="REVIEW"; withInn=false; }
                case MISSING_NUMBER -> { status="REVIEW"; withNumber=false; }
                case CONFLICT -> { status="REVIEW"; inn=clients.get(payer.id()==FIRST_ID+3?0:3).inn(); }
                case NO_CONTRACT -> { status="NO_CONTRACT"; number="MISSING-"+id; target=null; }
                case PROCESSED -> { status="SKIPPED"; operationStatus="PROCESSED"; linked=contract.id(); }
                case INVALID_INN -> { status="REVIEW"; inn=inn.substring(0,inn.length()-1)+(char)('0'+(inn.charAt(inn.length()-1)-'0'+1)%10); invalid.add(inn); }
                case UNUSUAL -> { }
                case UNKNOWN_NAME -> { status="REVIEW"; extra=", ФИО Неизвестнов Август Августович"; expectedNames.add("неизвестнов август августович"); }
                case ROLE_SWAP -> { status="REVIEW"; Client old=payer; payer=recipient; recipient=old; payerId=payer.id(); }
                case NAME_CONFLICT -> { status="REVIEW"; int person=differentPerson(payer,recipient);
                    extra=", ФИО "+PEOPLE[person][0]+" "+PEOPLE[person][1]+" "+PEOPLE[person][2]; expectedNames.add(PEOPLE[person][4]); }
                case SERVICE_PHRASE -> extra=", за услуги связи";
                case BENEFICIARY, DUPLICATE_NUMBER -> { status="REVIEW"; if(scenario==Scenario.DUPLICATE_NUMBER) target=null; }
                case INCOMPLETE_PARTY -> { status="REVIEW"; payerId=null; }
                case LONG_TEXT -> extra=", " + "Пояснение к оплате услуг. ".repeat(120);
                case OVER_LIMIT -> { status="REVIEW"; extra=", " + "Дополнительное описание. ".repeat(200); }
            }
            String action = new String[]{"Оплата услуг связи", "Перечисление за оборудование", "Арендная плата", "Взнос", "Авансовый платёж", "Оплата обучения"}[random.nextInt(6)];
            String contractLabel=new String[]{" по договору № "," по договору N "," дог. # "," договор "}[random.nextInt(4)];
            String displayedInn=inn;
            if(random.nextBoolean()) displayedInn=inn.substring(0,3)+" "+inn.substring(3,6)+" "+inn.substring(6);
            String suffix=new String[]{", без НДС",", период 10.2026",", основание: акт "+(i+1),", платёж согласно графику"}[random.nextInt(4)];
            String purpose = action + (withNumber ? contractLabel + number : "")
                    + (withInn ? ", ИНН " + displayedInn : "") + extra + suffix;
            if (scenario == Scenario.UNUSUAL)
                purpose = "ПЛАТЁЖ\nпо договору № «" + number.toLowerCase(java.util.Locale.ROOT).replace('-', '—')
                        + "», ИНН:\u00a0" + inn + ", назначение\u202fуточнено";
            if (!status.equals("SAFE")) safe=null;
            payments.add(new Payment(id, "GEN-"+config.seed()+"-"+id, purpose, operationStatus, linked,
                    payerId, recipient.id(), scenario==Scenario.INCOMPLETE_PARTY?null:payer.inn(), recipient.inn()));
            truth.add(new Truth(id, scenario, status, safe, target,
                    withInn && invalid.isEmpty()?List.of(inn):List.of(), List.copyOf(invalid), List.copyOf(expectedNames),
                    withNumber?List.of(number):List.of(), List.copyOf(orgs), third));
        }
        return new Dataset(config, clients, contracts, payments, truth);
    }

    private static List<Scenario> plan(Config config, SplittableRandom random) {
        long total = config.weights().values().stream().mapToLong(Integer::longValue).sum();
        var counts = new EnumMap<Scenario, Integer>(Scenario.class);
        List<Scenario> order = new ArrayList<>(List.of(Scenario.values()));
        int assigned=0;
        for (Scenario scenario : order) {
            int count=(int)((long)config.operations()*config.weights().getOrDefault(scenario,0)/total);
            counts.put(scenario,count); assigned+=count;
        }
        order.sort(java.util.Comparator.<Scenario>comparingLong(s -> -((long)config.operations()*config.weights().getOrDefault(s,0)%total)));
        for (int i=0;i<config.operations()-assigned;i++) counts.merge(order.get(i),1,Integer::sum);
        List<Scenario> plan = new ArrayList<>();
        counts.forEach((scenario,count)->{ for(int i=0;i<count;i++) plan.add(scenario); });
        for (int i=plan.size()-1;i>0;i--) Collections.swap(plan,i,random.nextInt(i+1));
        return plan;
    }

    private static int differentPerson(Client payer, Client recipient) {
        for(int i=0;i<PEOPLE.length;i++) {
            String[] person=PEOPLE[i];
            boolean payerSame=person[0].equals(payer.last()) && person[1].equals(payer.first());
            boolean recipientSame=person[0].equals(recipient.last()) && person[1].equals(recipient.first());
            if(!payerSame && !recipientSame) return i;
        }
        throw new IllegalStateException("Нужен независимый третий участник");
    }

    // Generation formula is separate from the engine's validation implementation.
    private static String legalInn(long prefix) {
        String value=Long.toString(prefix);
        return value+checksum(value, new int[]{2,4,10,3,5,9,4,6,8});
    }
    private static String personalInn(long prefix) {
        String value=Long.toString(prefix);
        value+=checksum(value,new int[]{7,2,4,10,3,5,9,4,6,8});
        return value+checksum(value,new int[]{3,7,2,4,10,3,5,9,4,6,8});
    }
    private static int checksum(String prefix,int[] weights) {
        int sum=0; for(int i=0;i<weights.length;i++) sum+=Integer.parseInt(prefix.substring(i,i+1))*weights[i];
        return sum%11%10;
    }
}
